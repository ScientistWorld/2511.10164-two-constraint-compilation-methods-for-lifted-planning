"""Train-slice evaluation.

Runs every compiler registered in ``outputs/compilers/*.json`` on the train
instances generated by ``train_lib`` and writes ``scoring/scores_train.json``.
Every number is recomputed from the compiled tasks the compilers return.
"""
from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import train_lib  # noqa: E402


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--registry", default=str(train_lib.ROOT / "outputs" / "compilers"))
    parser.add_argument("--output", default=str(train_lib.ROOT / "scoring" / "scores_train.json"))
    parser.add_argument("--experiments", nargs="*", default=None, help="optional subset (diagnostics only)")
    args = parser.parse_args()
    started = time.time()
    scores = train_lib.score_all(Path(args.registry), verbose=True, experiments=args.experiments,
                                 log=lambda m: print(m, flush=True))
    out = Path(args.output)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(scores, indent=2, sort_keys=True))
    print(f"wrote {out} in {time.time() - started:.1f}s", flush=True)


if __name__ == "__main__":
    main()
